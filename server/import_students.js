const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: { rejectUnauthorized: false }
});

function titleCase(str) {
  return str.toLowerCase().split(' ').map(word => 
    word.length > 0 ? word.charAt(0).toUpperCase() + word.slice(1) : ''
  ).join(' ').trim();
}

async function importStudents() {
  const lines = rawData.trim().split('\n');
  const client = await pool.connect();
  let successCount = 0;
  let skipCount = 0;
  
  try {
    const defaultPassword = await bcrypt.hash('password123', 10);
    console.log(`Starting import of ${lines.length} students...`);
    
    for (const line of lines) {
      const parts = line.split('\t');
      if (parts.length < 5) continue; // Ensure all columns exist
      
      const roll_number = parts[1].trim().toUpperCase();
      const full_name = titleCase(parts[2].trim());
      const branch = parts[3].trim().toUpperCase();
      const section = parts[4].trim().toUpperCase();
      const college_email = `${roll_number.toLowerCase()}@raghuenggcollege.in`; // Using a generic edu email format
      
      // Check if student already exists
      const checkResult = await client.query('SELECT id FROM users WHERE roll_number = $1', [roll_number]);
      if (checkResult.rows.length > 0) {
        skipCount++;
        continue; // Skip if they already exist
      }
      
      await client.query(
        'INSERT INTO users (full_name, roll_number, college_email, password_hash, role, branch, section) VALUES ($1, $2, $3, $4, $5, $6, $7)',
        [full_name, roll_number, college_email, defaultPassword, 'student', branch, section]
      );
      successCount++;
    }
    
    console.log(`✅ Import Complete! Added: ${successCount}, Skipped: ${skipCount} (Already Existed)`);
  } catch(e) {
    console.error('❌ Error during import:', e);
  } finally {
    client.release();
    pool.end();
  }
}

importStudents();
